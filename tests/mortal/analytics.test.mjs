import assert from 'node:assert/strict';
import {analyzeDecision,actionForDiscard,aggregateDecisions,combineAggregates,INDEX_VERSION} from '../../src/mortal/s42-analytics.mjs';
assert.equal(actionForDiscard('m0'),34);
assert.equal(actionForDiscard('z7'),33);
assert.equal(actionForDiscard('p5_'),13);
assert.equal(actionForDiscard('s5',true),37);
assert.equal(actionForDiscard('m9'),8);
const a=Array(46).fill(null);a[0]=0;a[1]=-1;a[2]=-4;a[37]=-6;
const base={best:0,qLegal:a};
let m=analyzeDecision(base,'m1',false);
assert.equal(m.agreement,true);assert.equal(m.rank,1);assert.equal(m.index,100);assert.equal(m.badCandidate,false);
m=analyzeDecision(base,'m2');
assert.equal(m.rank,2);assert.equal(m.badCandidate,false);assert(Math.abs(m.relativeGap-1/6)<1e-8);
m=analyzeDecision(base,'m3');
assert.equal(m.rank,3);assert.equal(m.badCandidate,true);assert.equal(m.index,33);
assert(Math.abs(m.stateValue-(-2.75))<1e-8);
assert(Math.abs(m.chosenAdvantage-(-1.25))<1e-8);
assert(Math.abs(m.chosenQ-(m.stateValue+m.chosenAdvantage))<1e-8);
assert.equal(analyzeDecision(base,'p2'),null);
assert.equal(analyzeDecision({best:37,qLegal:[...a.slice(0,37),4,...a.slice(38)]},'m3',true).action,37);
const agg=aggregateDecisions([{s42Review:analyzeDecision(base,'m1')},{s42Review:analyzeDecision(base,'m3')},{s42Review:null}]);
assert.equal(agg.count,2);assert.equal(agg.agreements,1);assert.equal(agg.suspected,1);assert.equal(agg.index,67);
const all=combineAggregates([agg,{...agg,count:2,agreements:0,suspected:2,index:40},{}]);
assert.equal(all.count,4);assert.equal(all.agreementRate,0.25);assert.equal(all.badCandidateRate,0.75);assert.equal(all.index,54);
assert.equal(INDEX_VERSION,'S42-relative-Q-v1');
console.log('PASS S42 analytics tests');
