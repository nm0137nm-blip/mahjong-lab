"""Compare S42 discard-only proxy learning curves using disjoint match cohorts.
Never loads holdout. Data is generated by coach-scale-corpus.yml.
Usage:
  python scripts/coach/pattern_scale.py /path/to/artifact-root report.json
Expected layout: scale-train-XX-questions/blind.json, corresponding
-reference/reference.json and -manifest/manifest.json; same for validation.
Requirements: numpy, scikit-learn (development only).
"""
import hashlib
import itertools
import json
import sys
from collections import Counter
from pathlib import Path
import numpy as np
from sklearn.ensemble import HistGradientBoostingRegressor
from pattern_pilot import load, fit, evaluate

MODEL_SHA='30381bf21389e2d25d3edf48fed11bf772336ef3daeee67d1bdae7fb9dd30cb4'

def read(path):
    return json.loads(path.read_text(encoding='utf8'))

def load_cohort(root,split):
    rows=[]; excluded=Counter(); hashes=set(); ids=set(); seeds=set(); groups=set()
    manifest_count=0; total=0; shards=[]; code_shas=set()
    for p in sorted(root.glob('scale-'+split+'-*-questions/blind.json')):
        prefix=p.parent.name.removesuffix('-questions')
        key=read(root/(prefix+'-reference')/'reference.json')
        manifest=read(root/(prefix+'-manifest')/'manifest.json')
        questions=read(p)['items']
        ks={k['id']:k for k in key}; qs={q['id']:q for q in questions}
        if len(ks)!=len(key) or len(qs)!=len(questions) or ks.keys()!=qs.keys() or ids.intersection(qs):
            raise ValueError('duplicate or mismatched IDs: '+prefix)
        if manifest['model']!=MODEL_SHA or not manifest.get('perMatchSeed') or not manifest.get('codeSha'):
            raise ValueError('unexpected model or missing seed/commit: '+prefix)
        code_shas.add(manifest['codeSha'])
        match_seeds=[m['matchSeed'] for m in manifest['matches']]
        match_ids=[m['prefix'] for m in manifest['matches']]
        if (len(match_seeds)!=10 or any(not isinstance(s,int) for s in match_seeds) or
            len(set(match_seeds))!=len(match_seeds) or seeds.intersection(match_seeds) or
            len(set(match_ids))!=len(match_ids) or groups.intersection(match_ids)):
            raise ValueError('invalid seed/match split: '+prefix)
        if sum(m['included'] for m in manifest['matches'])!=len(qs):
            raise ValueError('manifest count mismatch: '+prefix)
        seen_matches={m['prefix'] for m in manifest['matches']}
        if any(q['id'].rsplit('-',1)[0] not in seen_matches for q in questions):
            raise ValueError('unknown match: '+prefix)
        for q in questions:
            k=ks[q['id']]
            if k['model_sha256']!=MODEL_SHA or len(k['q'])!=46 or k['phase']!=q['phase']:
                raise ValueError('invalid reference')
            legal=sorted(x['action'] for x in q['actions'])
            actual=[i for i,v in enumerate(k['q']) if isinstance(v,(int,float)) and np.isfinite(v)]
            if legal!=actual or k['best'] not in legal or k['q'][k['best']]!=max(k['q'][a] for a in legal):
                raise ValueError('legal mask mismatch')
            raw=json.dumps([q['scene'],q['actions'],q.get('reaction')],sort_keys=True,ensure_ascii=False,separators=(',',':'))
            h=hashlib.sha256(raw.encode()).hexdigest()
            hashes.add(h)
        ids.update(qs); seeds.update(match_seeds); groups.update(match_ids)
        r,e=load(questions,key);rows.extend(r);excluded.update(e)
        total+=len(questions);manifest_count+=len(match_ids);shards.append(prefix)
    if not shards: raise ValueError('no artifacts for '+split)
    if len(code_shas)!=1: raise ValueError('mixed code revisions')
    return rows,dict(total=total,discard_only=len(rows),excluded=dict(excluded),matches=manifest_count,shards=shards,code_sha=next(iter(code_shas))),hashes,seeds

def baseline(r):
    return min(range(len(r['ids'])),key=lambda i:(r['F'][i,0],-r['F'][i,1],-r['F'][i,2],r['ids'][i]))

def expanded(r):
    F=r['F']; mn=F.min(axis=0); mx=F.max(axis=0); avg=F.mean(axis=0)
    return np.hstack([F,F-avg,F-mn,mx-F,np.tile(mn,(len(F),1)),np.tile(mx,(len(F),1))])

def train_reg(rows,depth):
    X=np.vstack([expanded(r) for r in rows]); Y=[]; W=[]
    for r in rows:
        q=r['q']; width=q.max()-q.min()
        Y.extend((q-q.min())/width if width else np.ones_like(q))
        W.extend([1/len(q)]*len(q))
    return HistGradientBoostingRegressor(max_iter=120,max_leaf_nodes=depth,l2_regularization=2.,learning_rate=.06,min_samples_leaf=20,random_state=259).fit(X,Y,sample_weight=W)

def stats(rows,pick):
    by_match={g:evaluate([r for r in rows if r['group']==g],pick) for g in sorted({r['group'] for r in rows})}
    return {'all':evaluate(rows,pick),'by_match':by_match}

def main():
    root=Path(sys.argv[1]); output=Path(sys.argv[2])
    tr,tm,th,ts=load_cohort(root,'train')
    va,vm,vh,vs=load_cohort(root,'validation')
    if tm['code_sha']!=vm['code_sha'] or ts&vs or th&vh:
        raise ValueError('train/validation overlap or code revision mismatch; quarantine cohort')
    if tm['matches']!=80 or vm['matches']!=20:
        raise ValueError('incomplete corpus; no training or promotion')
    if not tr or not va:
        raise ValueError('empty eligible sample')
    sc,lin=fit(tr)
    pickers={'baseline':baseline,'pairwise_linear':lambda r:int(np.argmax(lin.decision_function(sc.transform(r['F']))))}
    for depth in [7,15,31]:
        model=train_reg(tr,depth);pickers['gradient_'+str(depth)]=lambda r,m=model:int(np.argmax(m.predict(expanded(r))))
    results={name:stats(va,pick) for name,pick in pickers.items()}
    # Validation-only selection; no holdout access.
    chosen=min((n for n in results if n!='baseline'),key=lambda n:results[n]['all']['mean_normalized_gap'])
    # Fixed depth chosen before this larger experiment. Whole-match balanced
    # deterministic subsets; report dispersion across four seeded orders.
    groups=sorted({r['group'] for r in tr}); curve=[]
    for n in [4,10,20,40,len(groups)]:
        if n>len(groups) or n<1 or any(x['matches']==n for x in curve):continue
        trials=[]
        for seed in ([259] if n==len(groups) else [259,260,261,262]):
            rng=np.random.default_rng(seed)
            gs=set(rng.choice(groups,n,replace=False)); subset=[r for r in tr if r['group'] in gs]
            model=train_reg(subset,31)
            res=evaluate(va,lambda r:int(np.argmax(model.predict(expanded(r)))))
            trials.append({'seed':seed,'train_cases':len(subset),**res})
        curve.append({'matches':n,'trials':trials,'mean_normalized_gap':float(np.mean([r['mean_normalized_gap'] for r in trials])),'mean_exact_rate':float(np.mean([r['exact']/r['n'] for r in trials]))})
    score=results[chosen]['all']; baseline_score=results['baseline']['all']
    # This is only a screening proxy, never a release/coach certification gate.
    passes_screen=(score['exact']/score['n']>=.75 and score['mean_normalized_gap']<=.05 and score['mean_normalized_gap']<baseline_score['mean_normalized_gap'])
    report={'scope':'discard-only learned proxy, not an LLM coach or causal explanation','train':tm,'validation':vm,'holdout_opened':False,'results':results,'selected_on_validation':chosen,'fixed_depth_learning_curve':curve,'proxy_screen_pass':passes_screen,'production_go':False,'limitations':'Validation was used for selection. No inference of Mortal internal causes, no reaction or reach model, no independent explanation test, no production promotion. Holdout untouched.'}
    output.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    print(json.dumps({k:report[k] for k in ['scope','train','validation','selected_on_validation','proxy_screen_pass','production_go']},ensure_ascii=False))
if __name__=='__main__':main()
